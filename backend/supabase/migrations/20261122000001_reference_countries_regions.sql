--   also needs its legal-number rules in shared/src/company.ts (COMPANY_COUNTRY_RULES) and
--   in the companies_legal_numbers_check constraint.
-- regions: ISO 3166-2 ids (EG-C, SA-01, AE-DU). Egypt's 27 governorates use the names of the
--   web copy; Saudi Arabia's 13 regions and the UAE's 7 emirates are new.

create table public.countries (
  code           char(2) primary key check (code ~ '^[A-Z]{2}$'),
  name_ar        text not null check (char_length(name_ar) between 2 and 80),
  name_en        text not null check (char_length(name_en) between 2 and 80),
  dial_code      text check (dial_code ~ '^[1-9][0-9]{0,3}$'),
  company_signup boolean not null default false,
  sort           smallint not null default 100,
  active         boolean not null default true
);

comment on table public.countries is
  'Reference list (MW_003). company_signup = countries a shipping company can register from.';

create table public.regions (
  id           text primary key check (id ~ '^[A-Z]{2}-[A-Z0-9]{1,3}$'),
  country_code char(2) not null references public.countries (code),
  name_ar      text not null check (char_length(name_ar) between 2 and 80),
  name_en      text not null check (char_length(name_en) between 2 and 80),
  sort         smallint not null default 100,
  active       boolean not null default true,
  -- ISO 3166-2: the id starts with its country code
  constraint regions_country_prefix_check check (left(id, 2) = country_code),
  -- target of composite foreign keys "(country, region)": a region always belongs to its country
  constraint regions_country_id_key unique (country_code, id)
);

comment on table public.regions is
  'Reference list (MW_003): governorates (EG), regions (SA), emirates (AE). ISO 3166-2 ids.';

